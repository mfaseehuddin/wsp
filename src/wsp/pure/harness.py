"""wsp-pure: pure weight generation for an open-ended chat bot, following the protocol of Takehi et al. (2026).

The agent writes ONE file, experiments/pure/agents/<a>/model.py:

    def build() -> (family, cfg, params, groups)
        family: "transformer" (wsp.pure.transformer) or "ncm" (wsp.ncmchat.model, no Qwen parts)
        params: every tensor, generated by the agent's own reasoned code (no training, no pretrained weights)
        groups: provenance [{"name", "tensors", "mechanism", "why"}]

The agent never runs anything itself. Every forward pass goes through a pass tool, and each use costs one pass:
    dev    run dev cases (Stage X dev, tool-free) -> replies + mechanical checks
    chat   run up to 8 conversations the agent writes
    probe  one conversation; internals of the last reply (top-5 per step, attention targets / NCM levels)
check, spec, dev-list, examples, status and tokens are free. The session continues until every pass is used.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import sys
import time
from functools import lru_cache
from pathlib import Path

import torch

from wsp import progress

from . import transformer as TF

REPO = Path(__file__).resolve().parents[3]
ROOT = Path(os.environ.get("WSP_PURE_ROOT", REPO / "experiments/pure"))
QWEN_TOK = REPO / "models/Qwen2.5-0.5B"
PARAM_CAP = 300_000_000
MAX_NEW = 128
CHECKPOINTS = (10, 30, 50, 100)  # passes at which the model.py that ran is frozen to experiments/pure/frozen/


class BudgetExceeded(RuntimeError):
    pass


# ---------------------------------------------------------------- tokenizer


@lru_cache(None)
def tok():
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(QWEN_TOK)


def ids(text: str) -> list[int]:
    return tok()(text, add_special_tokens=False).input_ids


def special(name: str) -> int:
    return tok().convert_tokens_to_ids(name)


def user_turn(text: str) -> list[int]:
    return ids(f"<|im_start|>user\n{text}<|im_end|>\n<|im_start|>assistant\n")


# ---------------------------------------------------------------- ledger


def adir(a):
    return ROOT / "agents" / a


def read_ledger(a):
    p = adir(a) / ".ledger.json"
    if not p.exists():
        raise FileNotFoundError(f"no ledger for {a!r}")
    return json.loads(p.read_text())


def _dedupe(a, kind: str, request: str) -> None:
    """Refuse (without charging) an identical request on an unchanged model.py: greedy decoding is deterministic,
    so it would return exactly the same output and teach nothing."""
    led = read_ledger(a)
    key = hashlib.sha256((adir(a) / "model.py").read_bytes() + kind.encode() + request.encode()).hexdigest()[:20]
    seen = led.setdefault("seen", [])
    if key in seen:
        raise BudgetExceeded("identical request on an unchanged model.py: the output would be identical "
                             "(deterministic decoding). Not run, not counted. Change the model or the inputs.")
    seen.append(key)
    (adir(a) / ".ledger.json").write_text(json.dumps(led))


def _charge(a) -> int:
    led = read_ledger(a)
    if led["used"] >= led["budget"]:
        raise BudgetExceeded(f"all {led['budget']} passes used")
    led["used"] += 1
    (adir(a) / ".ledger.json").write_text(json.dumps(led))
    if led["used"] in CHECKPOINTS:  # freeze the exact model.py this pass runs (it was just built)
        src = adir(a) / "model.py"
        fz = ROOT / "frozen"
        fz.mkdir(exist_ok=True)
        dst = fz / f"{a}_p{led['used']:03d}.py"
        dst.write_bytes(src.read_bytes())
        meta = {"agent": a, "pass": led["used"], "time": time.strftime("%Y-%m-%d %H:%M:%S"),
                "sha256": hashlib.sha256(src.read_bytes()).hexdigest()}
        (fz / f"{a}_p{led['used']:03d}.json").write_text(json.dumps(meta))
        progress.say(f"checkpoint: froze {dst.name}")
    return led["used"]


def _log(a, rec):
    with open(adir(a) / "log.jsonl", "a") as f:
        f.write(json.dumps({"ts": time.time(), **rec}) + "\n")


def token_status(a):
    from wsp.bot.harness import context_tokens

    led = read_ledger(a)
    tf = adir(a) / ".transcript"
    now = context_tokens(tf.read_text().strip()) if tf.exists() else 0
    used = max(0, now - led.get("token_base", 0))
    return {"tokens_used": used, "token_budget": led["token_budget"], "remaining": led["token_budget"] - used}


# ---------------------------------------------------------------- build


def build(a: str, path: Path | None = None):
    path = path or adir(a) / "model.py"
    src = path.read_bytes()
    key = hashlib.sha256(src).hexdigest()[:16]
    cache = adir(a) / ".build" / f"{key}.pt" if path.parent == adir(a) else None
    if cache and cache.exists():
        d = torch.load(cache, weights_only=False)
        return d["family"], d["cfg"], d["P"], d["groups"], 0.0
    spec = importlib.util.spec_from_file_location(f"pure_model_{key}", path)
    mod = importlib.util.module_from_spec(spec)
    orig = torch.Tensor.backward

    def blocked(*_a, **_k):
        raise RuntimeError("no gradients: weights are written, not trained")

    torch.Tensor.backward = blocked
    t0 = time.time()
    try:
        with torch.no_grad():
            spec.loader.exec_module(mod)
            family, cfg, P, groups = mod.build()
    finally:
        torch.Tensor.backward = orig
    secs = time.time() - t0
    P = {k: torch.as_tensor(v).to(torch.float32) for k, v in P.items()}
    if family == "transformer":
        TF.validate(cfg, P)
    elif family == "ncm":
        from wsp.ncmchat import model as NCM

        assert not cfg.qwen_embed and not cfg.qwen_layers, "pure round: no pretrained (Qwen) parts"
        NCM.validate(cfg, P)
    else:
        raise AssertionError("family must be 'transformer' or 'ncm'")
    n = sum(v.numel() for v in P.values())
    assert n <= PARAM_CAP, f"{n:,} params > cap {PARAM_CAP:,}"
    if cache:
        cache.parent.mkdir(exist_ok=True)
        for old in cache.parent.glob("*.pt"):
            old.unlink()
        torch.save({"family": family, "cfg": cfg, "P": P, "groups": groups or []}, cache)
    return family, cfg, P, groups or [], secs


class Chat:
    def __init__(self, family, cfg, P):
        self.family, self.cfg, self.P = family, cfg, P
        self.end = special("<|im_end|>")
        if family == "transformer":
            self.cache = TF.Cache(cfg)
        else:
            from wsp.ncmchat import model as NCM

            self.NCM, self.cache = NCM, NCM.Cache(cfg)

    def turn(self, text: str, trace: bool = False) -> dict:
        if self.family == "transformer":
            g = TF.generate(self.cfg, self.P, self.cache, user_turn(text), self.end, MAX_NEW, trace)
            TF.forward(self.cfg, self.P, self.cache, [self.end] + ids("\n"))
            return {"reply": tok().decode(g["tokens"]), "trace": g}
        self.NCM.extend(self.cfg, self.P, self.cache, user_turn(text))
        out = self.NCM.reply(self.cfg, self.P, self.cache, trace)
        t = out["tokens"]
        t = t[: t.index(self.end)] if self.end in t else t
        self.NCM.extend(self.cfg, self.P, self.cache, t + [self.end] + ids("\n"))
        return {"reply": tok().decode(t), "trace": out}


def check_turn(reply: str, rule: dict):
    if not rule or set(rule) <= {"no_tools"}:
        return None
    r, c = reply.lower(), []
    if "exact" in rule:
        c.append(reply.strip() == rule["exact"])
    if "contains" in rule:
        c += [s.lower() in r for s in rule["contains"]]
    if "any" in rule:
        c.append(any(s.lower() in r for s in rule["any"]))
    if "absent" in rule:
        c += [s.lower() not in r for s in rule["absent"]]
    return all(c)


def run_cases(family, cfg, P, cases):
    res = []
    for j, case in enumerate(cases):
        done = [t["pass"] for r in res for t in r["turns"] if t["pass"] is not None]
        progress.say(f"case {j + 1}/{len(cases)} {case['id']} ({len(case['turns'])} turns); mechanical so far {sum(done)}/{len(done)}")
        ch, turns = Chat(family, cfg, P), []
        for t in case["turns"]:
            got = ch.turn(t["user"])["reply"]
            turns.append({"user": t["user"], "reply": got, "rubric": t.get("rubric", ""), "pass": check_turn(got, t.get("check", {}))})
        res.append({"id": case["id"], "category": case["category"], "turns": turns})
    return res


def _write_run(a, k, kind, text) -> str:
    d = adir(a) / "runs"
    d.mkdir(exist_ok=True)
    p = d / f"{kind}_{k:03d}.txt"
    p.write_text(text)
    return str(p.relative_to(REPO))


def _cases(sel: str):
    cases = json.loads((ROOT / "dev.json").read_text())
    if sel:
        want = set(sel.split(","))
        cases = [c for c in cases if c["id"] in want]
    return cases


# ---------------------------------------------------------------- commands


def cmd_check(a):
    family, cfg, P, groups, secs = build(a)
    return {"ok": True, "family": family, "config": cfg.to_dict(), "params": sum(v.numel() for v in P.values()),
            "nonzero": sum(int((v != 0).sum()) for v in P.values()), "groups": len(groups),
            "build_seconds": round(secs, 1)}


def cmd_dev(a, sel, note):
    family, cfg, P, _, _ = build(a)
    _dedupe(a, "dev", sel)
    k = _charge(a)
    res = run_cases(family, cfg, P, _cases(sel))
    lines, mech = [], []
    for r in res:
        lines.append(f"## {r['id']} ({r['category']})")
        for t in r["turns"]:
            mech.append(t["pass"]) if t["pass"] is not None else None
            mark = {True: "PASS", False: "FAIL", None: "----"}[t["pass"]]
            lines.append(f"[{mark}] U: {t['user'][:160]}\n       B: {t['reply'][:400]}\n       rubric: {t['rubric'][:160]}")
    f = _write_run(a, k, "dev", "\n".join(lines))
    fails = [f"{r['id']}: U: {t['user'][:80]} | B: {t['reply'][:120]}" for r in res for t in r["turns"] if t["pass"] is False]
    _log(a, {"cmd": "dev", "note": note, "pass": sum(mech), "of": len(mech)})
    return {"pass": k, "mechanical": f"{sum(mech)}/{len(mech)}", "turns": sum(len(r["turns"]) for r in res),
            "full_transcript": f, "failed_checks": fails[:15]}


def cmd_chat(a, convs_path, note):
    convs = json.loads(Path(convs_path).read_text())
    if convs and isinstance(convs[0], str):
        convs = [convs]
    convs = [c[:12] for c in convs[:8]]
    family, cfg, P, _, _ = build(a)
    _dedupe(a, "chat", json.dumps(convs))
    k = _charge(a)
    out = []
    for c in convs:
        ch = Chat(family, cfg, P)
        out.append([{"user": u, "bot": ch.turn(u)["reply"]} for u in c])
    f = _write_run(a, k, "chat", json.dumps(out, indent=1))
    _log(a, {"cmd": "chat", "note": note, "n": len(convs)})
    return {"pass": k, "conversations": out, "saved": f}


def cmd_probe(a, turns_path, note):
    turns = json.loads(Path(turns_path).read_text()) if Path(turns_path).exists() else [turns_path]
    family, cfg, P, _, _ = build(a)
    _dedupe(a, "probe", json.dumps(turns))
    k = _charge(a)
    ch = Chat(family, cfg, P)
    for t in turns[:-1]:
        ch.turn(t)
    if family == "transformer":
        prefix = ch.cache.n
        trace: list = []
        logits = TF.forward(cfg, P, ch.cache, user_turn(turns[-1]), trace)
        lines = []
        # attention of the LAST prompt position (where the first reply token is chosen), per layer/head
        for i, a_ in enumerate(trace):
            for h in range(a_.shape[0]):
                w = a_[h, -1]
                top = w.topk(min(3, w.numel()))
                lines.append(f"L{i}h{h}: " + ", ".join(f"pos{int(j)}={float(v):.2f}" for v, j in zip(top.values, top.indices)))
        top5 = [tok().decode([t]) for t in logits[-1].topk(5).indices.tolist()]
        ch2 = Chat(family, cfg, P)
        for t in turns[:-1]:
            ch2.turn(t)
        r = ch2.turn(turns[-1], trace=True)
        steps = [[tok().decode([t]) for t in s["top5"]] for s in r["trace"]["steps"][:12]]
        text = "\n".join([f"reply: {r['reply']}", f"first-token top5: {top5}", "top5 per reply step:"]
                         + [f"  {i}: {s}" for i, s in enumerate(steps)]
                         + [f"attention at the last prompt position (prefix length {prefix}, positions are absolute):"] + lines)
        f = _write_run(a, k, "probe", text)
        out = {"pass": k, "reply": r["reply"], "first_token_top5": top5, "steps_top5": steps[:8], "attention_file": f}
    else:
        r = ch.turn(turns[-1], trace=True)
        end = special("<|im_end|>")
        levels = []
        for l, L in enumerate(r["trace"]["levels"]):
            tk = ch.NCM.decode_latent(cfg, P, L["z"]).argmax(-1).tolist()
            tk = tk[: tk.index(end)] if end in tk else tk
            levels.append({"level": l, "codes": r["trace"]["codes"][l][:64], "decoded_so_far": tok().decode(tk)})
        f = _write_run(a, k, "probe", json.dumps(levels, indent=1))
        out = {"pass": k, "reply": r["reply"], "levels": levels}
    _log(a, {"cmd": "probe", "note": note})
    return out


def cmd_test(a, cases_path, out_path, model_path=""):
    family, cfg, P, _, _ = build(a, Path(model_path) if model_path else None)
    res = run_cases(family, cfg, P, json.loads(Path(cases_path).read_text()))
    out = {"agent": a, "model": model_path or "current", "family": family, "results": res,
           "params": sum(v.numel() for v in P.values())}
    if out_path:
        Path(out_path).write_text(json.dumps(out, indent=1))
    mech = [t["pass"] for r in res for t in r["turns"] if t["pass"] is not None]
    return {"agent": a, "mechanical": f"{sum(mech)}/{len(mech)}", "turns": sum(len(r["turns"]) for r in res), "out": out_path}


def talk(a):
    family, cfg, P, _, _ = build(a)
    ch = Chat(family, cfg, P)
    print("wsp-pure chat. Ctrl-D to quit.")
    for line in sys.stdin:
        print("bot:", ch.turn(line.strip())["reply"])


def _admin():
    if os.environ.get("WSP_ADMIN") != "1":
        sys.exit("admin command: agents must not use this")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="wsp-pure")
    sub = ap.add_subparsers(dest="cmd", required=True)
    A, N = ("--agent", str, None), ("--note", str, "")
    spec = {"spec": [], "dev-list": [("--ids", str, "")], "examples": [], "tokenize": [("--text", str, None)],
            "status": [A], "tokens": [A], "check": [A], "dev": [A, ("--ids", str, ""), N],
            "chat": [A, ("--convs", str, None), N], "probe": [A, ("--turns", str, None), N],
            "init": [A, ("--budget", int, None), ("--tokens", int, None)],
            "test": [A, ("--cases", str, None), ("--out", str, ""), ("--model", str, "")], "talk": [A]}
    for name, args in spec.items():
        s = sub.add_parser(name)
        for flag, typ, default in args:
            s.add_argument(flag, type=typ, default=default, required=default is None)
    a = ap.parse_args(argv)
    if a.cmd in ("dev", "chat", "probe", "test", "check"):
        progress.say(f"log: {progress.start(ROOT, a.cmd, getattr(a, 'agent', None))}")
    try:
        if a.cmd == "spec":
            out = {"families": ["transformer (src/wsp/pure/transformer.py)", "ncm (src/wsp/ncmchat/model.py, without Qwen parts)"],
                   "vocab": 151936, "tokenizer": "Qwen2.5 BPE (151,665 tokens used; embedding rows 151,936)",
                   "chat_format": "<|im_start|>user\\n{msg}<|im_end|>\\n<|im_start|>assistant\\n{reply}<|im_end|>\\n",
                   "special_ids": {s: special(s) for s in ("<|im_start|>", "<|im_end|>", "<|endoftext|>")},
                   "max_new_tokens_per_reply": MAX_NEW, "param_cap": PARAM_CAP, "dev_cases": len(_cases(""))}
        elif a.cmd == "dev-list":
            out = _cases(a.ids)
        elif a.cmd == "examples":
            out = (ROOT / "examples" / "README.md").read_text()
            print(out)
            return
        elif a.cmd == "tokenize":
            t = ids(a.text)
            out = {"ids": t, "pieces": [tok().decode([i]) for i in t]}
        elif a.cmd == "status":
            led = read_ledger(a.agent)
            out = {"passes_budget": led["budget"], "passes_used": led["used"], "passes_left": led["budget"] - led["used"]}
        elif a.cmd == "tokens":
            out = token_status(a.agent)
        elif a.cmd == "check":
            out = cmd_check(a.agent)
        elif a.cmd == "dev":
            out = cmd_dev(a.agent, a.ids, a.note)
        elif a.cmd == "chat":
            out = cmd_chat(a.agent, a.convs, a.note)
        elif a.cmd == "probe":
            out = cmd_probe(a.agent, a.turns, a.note)
        elif a.cmd == "init":
            _admin()
            adir(a.agent).mkdir(parents=True, exist_ok=True)
            (adir(a.agent) / ".ledger.json").write_text(json.dumps({"budget": a.budget, "used": 0, "token_budget": a.tokens, "token_base": 0}))
            out = read_ledger(a.agent)
        elif a.cmd == "test":
            _admin()
            out = cmd_test(a.agent, a.cases, a.out, a.model)
        elif a.cmd == "talk":
            talk(a.agent)
            return
    except (BudgetExceeded, FileNotFoundError, AssertionError) as e:
        out = {"error": str(e)}
    except Exception as e:  # noqa: BLE001 -- a model.py that crashes during build is the agent's bug; report it, don't charge
        out = {"error": f"{type(e).__name__}: {e}"}
    if a.cmd in ("dev", "chat", "probe", "test", "check"):
        progress.say("done: " + json.dumps(out)[:300])
    print(json.dumps(out, indent=1))
