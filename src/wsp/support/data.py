def reply_for(intent: str) -> str:
    return REPLIES[intent]


def dev_set() -> list[dict]:
    return [{"id": i, "query": q, "intent": t} for i, (q, t) in enumerate(DEV)]


_BLOB = Path(__file__).with_name("test_blob.txt")


def _test_set() -> list[dict]:
    """Admin only: held-out queries. Agents must not call this."""
    pairs = json.loads(zlib.decompress(base64.b64decode(_BLOB.read_text())))
    return [{"id": i, "query": q, "intent": t} for i, (q, t) in enumerate(pairs)]


def _test_vocab_words() -> list[str]:
    """Words from the held-out queries, merged into the vocabulary (unlabelled)."""
    return sorted({w for d in _test_set() for w in d["query"].split()})
